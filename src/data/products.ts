export type StockStatus = "in-stock" | "low-stock" | "out-of-stock";
export type ProductBadge = "sale" | "new";

export interface Product {
  id: string;
  slug: string;
  name: string;
  spec: string;
  category: string;
  /** Undefined for parts/accessories that aren't sold by brand-of-machine (e.g. a RAM kit). */
  brand?: string;
  /** GB of unified/system memory — only meaningful for laptops & desktops. */
  ram?: number;
  /** GB of primary storage — only meaningful for laptops & desktops. */
  storage?: number;
  price: number;
  compareAtPrice?: number;
  rating: number;
  reviewCount: number;
  stock: StockStatus;
  badge?: ProductBadge;
  /** ISO date; used for the "Newest" sort. */
  createdAt?: string;
}

